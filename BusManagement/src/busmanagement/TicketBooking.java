    private void GetPassenger(){
        try{
            Con = DriverManager.getConnection("jdbc:mysql://localhost:3306/busmanagedb","root","");
            St = Con.createStatement();
            String Query = "select * from PassengersTbl";
            Rs = St.executeQuery(Query);
            while(Rs.next()){
                String PId  = String.valueOf(Rs.getInt("PId"));
                PassIdCb.addItem(PId);
            }
        }catch (Exception e){   
        } 
    }
    
    private void GetBus(){
        try{
            Con = DriverManager.getConnection("jdbc:mysql://localhost:3306/busmanagedb","root","");
            St = Con.createStatement();
            String Query = "select * from BusTbl";
            Rs = St.executeQuery(Query);
            while(Rs.next()){
                String FCode  = Rs.getString("BName");
                FCodeCb.addItem(FCode);
            }
        }catch (Exception e){   
        } 
    }
    
    private void GetPassengerData(){
        String Query = "select * from PassengersTbl where PId ="+PassIdCb.getSelectedItem().toString();
        Statement St;
        ResultSet  Rs;
        try {
            Con = DriverManager.getConnection("jdbc:mysql://localhost:3306/busmanagedb","root","");
            St = Con.createStatement();
            Rs = St.executeQuery(Query);
            if(Rs.next()){
                PassNameTb.setText(Rs.getString("PName"));
                PGenTb.setText(Rs.getString("PGen"));
                RouteTb.setText(Rs.getString("PRoute"));
                DeptTb.setText(Rs.getString("PDept"));
            } 
        }catch (Exception e){
            
        } 
    }
