    private void BookBtnMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_BookBtnMouseClicked
       if( PassIdCb.getSelectedIndex()== -1 || FCodeCb.getSelectedIndex()== -1 || AmntTb.getText().isEmpty()) 
         {
             JOptionPane.showMessageDialog(this, "Missing Information");
         } else {
           try{
               CountBus();
               Con = DriverManager.getConnection("jdbc:mysql://localhost:3306/busmanagedb","root","");
               PreparedStatement Add = Con.prepareStatement("insert into BookingTbl values (?,?,?,?,?,?,?)");
               Add.setInt(1, TId);
               Add.setString(2,PassNameTb.getText());
               Add.setString(3,FCodeCb.getSelectedItem().toString());
               Add.setString(4,PGenTb.getText());
               Add.setString(5,RouteTb.getText());
               Add.setInt(6, Integer.valueOf(AmntTb.getText()));
               Add.setString(7,DeptTb.getText());
               int row = Add.executeUpdate();
               JOptionPane.showMessageDialog(this, " Ticket Booked");
               Con.close();
               DisplayBooking();
               Clear();
           }  catch (Exception e){
               JOptionPane.showMessageDialog(this,e);
           }
         }
    }//GEN-LAST:event_BookBtnMouseClicked

